"""estampo.toml writer: one [[parts]] per delivered STL plus slicer overrides from profile.json.

Pure text, no estampo dependency. Keys target estampo 0.4.x (docs/config.md).
"""

import json
import os


def estampo_toml(stl_files: list[str], profile: dict) -> str:
    """Return estampo.toml text for `stl_files` (names, already in print pose)."""
    motion = profile.get("motion") or {}
    names = (profile.get("slicer") or {}).get("estampo") or {}
    lines = ["# Generated by cq-design for estampo 0.4.x. STLs are already in print pose.", ""]
    lines += ["[slicer]", 'engine = "orca"', "", "[slicer.orca]"]
    for key in ("printer", "process"):
        lines.append(
            f"{key} = {json.dumps(names[key])}"
            if key in names
            else f'# {key} = "<Orca {key} profile>"  (set slicer.estampo.{key} in profile.json)'
        )
    lines.append(
        f"filaments = {json.dumps(names['filaments'])}"
        if "filaments" in names
        else '# filaments = ["<Orca filament profile name>"]  (set slicer.estampo.filaments)'
    )
    overrides = []
    if "layer_height_mm" in motion:
        overrides.append(f"layer_height = {motion['layer_height_mm']}")
    if "infill_density" in motion:
        overrides.append(f'sparse_infill_density = "{round(motion["infill_density"] * 100)}%"')
    if overrides:
        lines += ["", "[slicer.orca.overrides]", *overrides]
    for name in stl_files:
        lines += ["", "[[parts]]", f"file = {json.dumps(name)}", "rotate = [0, 0, 0]"]
    return "\n".join(lines) + "\n"


def write_estampo_toml(stl_paths: list[str], profile: dict, out_dir: str) -> str:
    """Write `estampo.toml` into `out_dir` for `stl_paths` (siblings of it); return its path."""
    path = os.path.join(out_dir, "estampo.toml")
    with open(path, "w", encoding="utf-8") as f:
        f.write(estampo_toml([os.path.basename(p) for p in stl_paths], profile))
    return path
