import cadquery as cq

PTS = [
    (-0.05430806, 0.05735744), (-0.05430806, -0.05851911), (-0.04704762, -0.05851911),
    (-0.0383351, -0.00217813), (0.00232334, -0.00217813), (0.0116167, -0.06200412),
    (0.01742505, -0.06200412), (0.01452087, 0.01030982), (-0.02875133, 0.01030982),
    (-0.0450147, 0.05735744),
]  # fmt: skip
DEPTH = 0.1016
SCALE = 7.38186180173805

result = (
    cq.Workplane("XY")
    .polyline([(x * SCALE, y * SCALE) for x, y in PTS])
    .close()
    .extrude(DEPTH * SCALE)
    .rotate((0, 0, 0), (1, 0, 0), -90)
    .rotate((0, 0, 0), (0, 0, 1), -90)
)
